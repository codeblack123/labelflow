export const applyTheme = (themeName: ThemeName | string) => {
    const themeStr = (THEMES[themeName as ThemeName] ? themeName : 'Biru Tua') as ThemeName;
    const colors = THEMES[themeStr];

    const root = document.documentElement;
    Object.entries(colors).forEach(([shade, rgbValue]) => {
        root.style.setProperty(`--theme-${shade}`, rgbValue);
    });

    // Set primary variables for dynamic css matching
    root.style.setProperty('--primary', `rgb(${colors[600]})`);
    root.style.setProperty('--primary-hover', `rgb(${colors[700]})`);
    root.style.setProperty('--primary-light', `rgb(${colors[50]})`);
    root.style.setProperty('--primary-border', `rgb(${colors[200]})`);
    root.setAttribute('data-theme', themeStr);

    localStorage.setItem('app_theme', themeStr);
    window.dispatchEvent(new Event('themechange'));
};
